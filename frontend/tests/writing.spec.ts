import { test, expect } from './studio-fixture'

test('大纲审核、分集规划、场次对白编辑、重启与上游过期', async ({ page, studio }) => {
  await page.goto(studio.url)
  await page.getByRole('button', { name: '＋ 新建项目' }).click()
  await page.getByPlaceholder('输入短剧名称').fill('沿河邮局')
  await page.getByRole('button', { name: '创建项目', exact: true }).click()
  await page.getByRole('navigation').getByRole('button', { name: '编剧工作台' }).click()
  await expect(page.getByText('Mock 模拟模型', { exact: true })).toBeVisible()
  await page.getByLabel('创作意图').fill('年轻站员寻找一封遗失的信')
  await page.getByRole('button', { name: '生成故事大纲' }).click()
  await expect(page.getByLabel('剧名', { exact: true })).toHaveValue('末班信 · Mock')
  await page.getByLabel('剧名', { exact: true }).fill('沿河邮局')
  await page.getByRole('button', { name: '保存新版本' }).click()
  await expect(page.getByLabel('修订历史').locator('option:checked')).toHaveText(/版本 2 · 草稿/)
  await page.getByRole('button', { name: '分集规划', exact: true }).click()
  await expect(page.getByRole('button', { name: '生成分集规划' })).toBeDisabled()
  await page.getByRole('button', { name: '故事大纲', exact: true }).click()
  await page.getByRole('button', { name: '审核通过' }).click()
  await expect(page.getByLabel('修订历史').locator('option:checked')).toHaveText(/已审核/)
  await page.getByRole('button', { name: '分集规划', exact: true }).click()
  await page.getByRole('button', { name: '生成分集规划' }).click()
  const ep = page.getByRole('button', { name: /第 1 集 ·/ })
  await expect(ep).toBeVisible()
  await ep.click()
  await page.getByRole('button', { name: '生成分集剧本' }).click()
  await expect(page.getByLabel('台词', { exact: true })).toHaveValue('这封信，还来得及送到。')
  await page.getByLabel('台词', { exact: true }).fill('还有一班车，我们赶得上。')
  await page.getByRole('button', { name: '保存新版本' }).click()
  await expect(page.getByLabel('修订历史').locator('option:checked')).toHaveText(/版本 2/)
  await page.getByRole('button', { name: '审核通过' }).click()
  await expect(page.getByLabel('修订历史').locator('option:checked')).toHaveText(/已审核/)
  await studio.restart()
  await page.reload()
  await ep.click()
  await expect(page.getByLabel('台词', { exact: true })).toHaveValue('还有一班车，我们赶得上。')
  const speaker = page.getByRole('combobox', { name: '说话人', exact: true })
  const originalName = '林青'
  await expect(speaker.locator('option:checked')).toHaveText(originalName)
  await page.getByRole('button', { name: '故事大纲', exact: true }).click()
  await page.getByLabel('世界观').fill('暴雨过后的山城，渡轮停航。')
  await page.getByLabel('名称', { exact: true }).first().fill('顾言')
  await page.getByLabel('引用标识', { exact: true }).first().fill('gu')
  await page.getByRole('button', { name: '保存新版本' }).click()
  await expect(page.getByLabel('修订历史').locator('option:checked')).toHaveText(/版本 3/)
  await ep.click()
  await expect(page.getByLabel('修订历史').locator('option:checked')).toHaveText(/上游已变更/)
  await expect(page.getByRole('button', { name: '生成分集剧本' })).toBeDisabled()
  await expect(speaker.locator('option:checked')).toHaveText(originalName)
  await page.getByRole('button', { name: '故事大纲', exact: true }).click()
  await page.getByRole('button', { name: '审核通过' }).click()
  await expect(page.getByLabel('修订历史').locator('option:checked')).toHaveText(/版本 3 · 已审核/)
  await page.getByRole('button', { name: '分集规划', exact: true }).click()
  await page.getByRole('button', { name: '生成分集规划' }).click()
  await expect(page.getByLabel('修订历史').locator('option:checked')).toHaveText(/版本 2 · 待审核/)
  await ep.click()
  await expect(speaker.locator('option:checked')).toHaveText(originalName)
  await page.getByRole('button', { name: '按当前规划修订' }).click()
  await page.getByRole('checkbox', { name: '顾言' }).check()
  await speaker.selectOption('gu')
  await page.getByRole('button', { name: '保存新版本' }).click()
  await expect(page.getByLabel('修订历史').locator('option:checked')).toHaveText(/版本 3 · 草稿/)
  await expect(speaker.locator('option:checked')).toHaveText('顾言')
  await page.getByRole('navigation').getByRole('button', { name: '任务中心' }).click()
  await page.locator('.task-row').filter({ hasText: '分集剧本' }).click()
  await page.getByRole('link', { name: '打开对应稿件' }).click()
  await expect(page.getByRole('heading', { name: '分集剧本', exact: true })).toBeVisible()
  await expect(page.getByLabel('修订历史').locator('option:checked')).toHaveText(/版本 1/)
  await expect(speaker.locator('option:checked')).toHaveText(originalName)
})
