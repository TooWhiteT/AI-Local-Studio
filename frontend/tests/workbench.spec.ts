import { test, expect } from './studio-fixture'

test('蓝白浅色主题覆盖页面、导航和弹窗控件', async ({ page, studio }) => {
  const white = 'rgb(255, 255, 255)'
  const blue = 'rgb(36, 94, 219)'
  await page.goto(studio.url)
  await expect(page.locator('html')).toHaveCSS('background-color', 'rgb(243, 247, 253)')
  await expect(page.locator('.sidebar')).toHaveCSS('background-color', white)
  await expect(page.locator('.panel')).toHaveCSS('background-color', white)

  const selected = page.getByRole('navigation').getByRole('button', { name: '项目库' })
  await selected.focus()
  await expect(selected).toHaveCSS('outline-color', blue)
  await expect(selected).toHaveCSS('background-color', 'rgb(231, 239, 255)')

  const create = page.getByRole('button', { name: '＋ 新建项目' })
  await expect(create).toHaveCSS('background-color', blue)
  await create.hover()
  await expect(create).toHaveCSS('background-color', 'rgb(29, 79, 193)')
  await create.click()
  await expect(page.locator('.modal-card')).toHaveCSS('background-color', white)
  const title = page.getByPlaceholder('输入短剧名称')
  await title.fill('主题预览')
  await expect(title).toHaveCSS('caret-color', blue)
  await expect(page.getByRole('button', { name: '创建项目', exact: true })).toHaveCSS('background-color', blue)
  await page.getByRole('button', { name: '取消' }).click()
  await expect(page.locator('.modal-card')).toBeHidden()
})

test('创建项目和资产、生成图片、刷新与重启查询、失败重试', async ({ page, studio }) => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto(studio.url)
  await page.getByRole('button', { name: '＋ 新建项目' }).click()
  await page.getByPlaceholder('输入短剧名称').fill('夜航')
  await page.getByRole('button', { name: '创建项目', exact: true }).click()
  await expect(page.getByRole('heading', { name: '资产生成' })).toBeVisible()
  await page.getByRole('button', { name: '＋ 新建资产' }).click()
  await page.getByPlaceholder('输入资产名称').fill('月台')
  await page.getByRole('button', { name: '创建资产', exact: true }).click()
  await page.getByRole('button', { name: '提交图片任务' }).click()
  await expect(page.getByRole('img', { name: '月台 版本 1' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('img', { name: '月台 版本 1' })).toBeVisible()
  await studio.restart()
  await page.reload()
  const image = page.getByRole('img', { name: '月台 版本 1' })
  await expect(image).toBeVisible()
  await expect.poll(() => image.evaluate((el: HTMLImageElement) => el.naturalWidth)).toBe(320)
  await page.getByRole('textbox', { name: '画面描述' }).fill('[mock:fail-once]')
  await page.getByRole('button', { name: '提交图片任务' }).click()
  await expect(page.locator('.latest-task')).toContainText('失败')
  await page.getByRole('button', { name: '查看详情' }).click()
  await page.getByRole('button', { name: '重试任务' }).click()
  await expect(page.locator('.detail-head')).toContainText('已完成')
  await expect(page.locator('.attempt')).toHaveCount(2)
  await expect(page.locator('.attempt').first()).toContainText('失败')
  expect(errors).toEqual([])
})
test('编辑模板版本和项目归档，手机布局可用', async ({ page, studio }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(studio.url)
  await page.getByRole('button', { name: '工作流', exact: true }).click()
  await page.getByRole('button', { name: '编辑绑定' }).click()
  await page.getByPlaceholder('输入尚未发布的版本').fill('2')
  await page.getByRole('button', { name: '发布新版本' }).click()
  await expect(page.locator('.flow-card')).toHaveCount(2)
  await page.getByRole('button', { name: '项目库', exact: true }).click()
  await page.getByRole('button', { name: '＋ 新建项目' }).click()
  await page.getByPlaceholder('输入短剧名称').fill('原项目')
  await page.getByRole('button', { name: '创建项目', exact: true }).click()
  await expect(page.getByRole('heading', { name: '资产生成' })).toBeVisible()
  await page.getByRole('button', { name: '项目库', exact: true }).click()
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  await page.getByPlaceholder('输入短剧名称').fill('重命名项目')
  await page.getByRole('button', { name: '保存项目' }).click()
  await expect(page.locator('.project-row')).toContainText('重命名项目')
  await page.getByRole('button', { name: '归档', exact: true }).click()
  await page.getByRole('button', { name: /已归档/ }).click()
  await page.getByRole('button', { name: '恢复', exact: true }).click()
  await page.getByRole('button', { name: /制作中/ }).click()
  await expect(page.locator('.project-row')).toContainText('重命名项目')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
